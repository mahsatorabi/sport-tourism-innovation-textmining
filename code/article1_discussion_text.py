SEC_70 = [
    (
        "This paper asked how innovation and entrepreneurship are conceptually organised "
        "in sport tourism and sport-event research. The answer, on the evidence of a "
        "focused Scopus corpus, is that the field is multi-core. Destination-market "
        "systems, entrepreneurial event ventures, digital–fan infrastructures, green "
        "transition discourses and Olympic/mega-event hosting form distinguishable "
        "themes. Innovation and entrepreneurship occupy adjacent rather than identical "
        "network positions. What holds the literature together is less a single master "
        "construct than a set of bridging terms—management, model, development, social "
        "and digital among them—through which specialised conversations remain mutually "
        "intelligible. Since 2019, sustainability and digital vocabularies have "
        "intensified, reshaping the edges of the map without erasing its event–tourism "
        "spine. For researchers and practitioners alike, the useful next step is not to "
        "hunt for one definition of sport-tourism innovation, but to work more carefully "
        "with the plurality the literature already contains."
    ),
]

