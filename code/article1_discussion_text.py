SEC_51 = [
    (
        "The results do not describe a tidy, single-theme literature. They describe a "
        "field that has grown sideways. Destination-market writing, entrepreneurial "
        "event venturing, digital–fan infrastructures, green-transition talk and "
        "Olympic hosting each carry their own centre of gravity. That plural structure "
        "is consistent with broader sport-tourism maps that already separate behaviour, "
        "events, sustainability and development (Arici et al., 2025). What our narrower "
        "cut adds is evidence that innovation and entrepreneurship do not sit evenly "
        "across those clusters. Innovation is pulled toward event technologies and "
        "management language; entrepreneurship is pulled toward markets, brands, services "
        "and social participation. Treating the two words as synonyms therefore misreads "
        "the corpus."
    ),
    (
        "The bridging pattern helps explain why the field can still feel connected. "
        "Management and model occupy the strongest betweenness positions. That is not "
        "especially romantic, but it is revealing. Integration happens less through a "
        "hero concept such as “ecosystem” or “disruption” than through practical "
        "organisational vocabulary that can travel between destination theory, venture "
        "talk and digital operations. Development and social play a similar role for "
        "sustainability and community-facing debates. Digital appears both as a topical "
        "cluster and as a bridge, which fits recent arguments that smart technologies "
        "now cut across experience, marketing and sustainability stages of events "
        "(Thelen & Kim, 2024)."
    ),
    (
        "Temporally, the post-2019 rise of sustainability, green/carbon, urban/city and "
        "blockchain/stadium terms suggests the field is being rewritten under twin "
        "pressures: environmental accountability and socio-technical change. This echoes "
        "earlier calls to couple sport entrepreneurship with tourism and environmental "
        "agendas (González-Serrano et al., 2020) and the wider post-pandemic reset in "
        "tourism systems (Gössling et al., 2021). In short, the map is not static. The "
        "multi-core structure is becoming greener and more digital at the edges while "
        "retaining an event–tourism managerial spine."
    ),
]

SEC_52 = [
    (
        "Theoretically, the study supports a differentiated rather than unitary view of "
        "sport-tourism innovation. Ratten’s (2012, 2018) broad account of sport "
        "entrepreneurship already resisted reducing entrepreneurship to start-up creation; "
        "our network evidence pushes that point further by locating entrepreneurship in a "
        "market–social neighbourhood distinct from digital-innovation infrastructures. "
        "One implication is that theories of sport-tourism innovation should specify "
        "which layer they address—product-market venturing, socio-technical systems, "
        "destination upgrading, or mega-event hosting politics—instead of invoking "
        "innovation as an undifferentiated virtue."
    ),
    (
        "A second implication concerns relational structure. Following Callon et al. "
        "(1983) and later science-mapping practice (van Eck & Waltman, 2014; Donthu "
        "et al., 2021), we treat bridging concepts as clues to how a literature holds "
        "itself together. The prominence of management and model suggests that "
        "integrative theorising in this niche is still largely organisational and "
        "schematic. That is an opportunity: richer theories of platforms, entrepreneurial "
        "ecosystems or institutional entrepreneurship could be tested against a field "
        "that currently brokers meaning through thinner managerial terms. It is also a "
        "caution. If every paper routes its contribution through “management implications” "
        "and “proposed models,” conceptual consolidation may look stronger than it is."
    ),
    (
        "Third, the modular Olympic/mega-event community warns against absorbing all "
        "event innovation under one heading. Legacy and leverage debates (Preuss, 2007; "
        "Chalip, 2006) remain specialised. Collapsing them into general sport-event "
        "entrepreneurship risks both overstating unity and understating the politics of "
        "hosting. A useful theoretical move is to keep mega-event innovation and "
        "everyday event venturing in view as related but non-identical positions—exactly "
        "the pattern the topic and network solutions recovered."
    ),
]

