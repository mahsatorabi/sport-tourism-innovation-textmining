# --- 6. Limitations ---
SEC_61 = [
    (
        "Several limits should be kept in view. First, the corpus is Scopus-based and "
        "English-language after filtering. Coverage biases in Scopus are well documented "
        "(Mongeon & Paul-Hus, 2016), and relevant work in other languages or databases "
        "may be missing. Second, subsetting on sport tourism/events plus innovation/"
        "entrepreneurship improves focus but also excludes adjacent papers that discuss "
        "innovation without those exact markers. Third, NMF topics and network bridges "
        "are corpus artefacts. They are interpreted, not discovered as natural kinds. "
        "Alternative tokenisation, stopword choices or topic numbers would shift margins "
        "even if the broad multi-core reading proved stable in our checks."
    ),
    (
        "Fourth, titles, abstracts and keywords are compressed texts. They favour "
        "canonical vocabulary and under-represent methods detail or negative findings. "
        "Fifth, betweenness identifies textual brokerage, not organisational power in "
        "real destinations. Finally, the 2019 cut for temporal comparison is analytically "
        "convenient and substantively motivated, but it is still a single breakpoint; "
        "finer year-by-year dynamics would need a larger specialised corpus."
    ),
]

SEC_62 = [
    (
        "Future research can move in three directions. Empirically, mixed-method designs "
        "could test whether the five topics correspond to distinct practitioner "
        "communities—digital event teams, entrepreneurial SMEs, destination marketers, "
        "sustainability officers and mega-event organising bodies. Conceptually, scholars "
        "could build mid-range theories that specify mechanisms linking entrepreneurship "
        "and digital innovation rather than treating bridge terms such as management as "
        "enough. Methodologically, comparative maps across Web of Science and Scopus, "
        "or multilingual corpora, would probe robustness. There is also room for "
        "design-oriented work that turns bridging concepts into intervention points—"
        "for example, evaluating whether shared development models actually improve "
        "coordination between venture ecosystems and digital event infrastructures."
    ),
]

